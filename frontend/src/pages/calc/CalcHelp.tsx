import { useRef, type MouseEvent } from "react";
import { createPortal } from "react-dom";
import { useTopbarTrailingSlot } from "../../app/topbarSlot";

/**
 * Справка листа «Расчёт»: назначение, порядок работы и смысл показателей.
 *
 * Тем же приёмом, что `pages/economics/EconomicsHelp.tsx`: круглая кнопка «?»
 * в шапке, нативный `dialog`. Сюда же ушла вторая фраза подсказки панели
 * паспортов — про кнопку «Экономика»: на одном экране ей нет места, а знать
 * её нужно один раз. Формулировки про q и негабарит пересказывают
 * `Blast.py::optimize_blast` — при изменении подбора сверьте текст.
 */
export function CalcHelp() {
  const ref = useRef<HTMLDialogElement>(null);
  // Кнопка в правом углу шапки; без слота (тесты без AppShell) — на странице.
  const trailingSlot = useTopbarTrailingSlot();

  // Esc нативный `dialog` обрабатывает сам; клик по подложке бьёт по самому
  // `<dialog>`, клик по содержимому — по вложенным элементам.
  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  const openButton = (
    <button
      type="button"
      className="topbar-icon-button"
      aria-label="Справка"
      title="Справка"
      onClick={() => ref.current?.showModal()}
    >
      ?
    </button>
  );

  return (
    <>
      {trailingSlot ? createPortal(openButton, trailingSlot) : openButton}
      <dialog ref={ref} className="calc-help" aria-labelledby="calc-help-title" onClick={onBackdropClick}>
        <header>
          <b id="calc-help-title">Подбор параметров БВР</b>
          <button type="button" aria-label="Закрыть" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="calc-help-body">
          <p>
            Лист подбирает параметры буровзрывных работ для блока: сетку скважин под
            каждый диаметр коронки, удельный расход ВВ и схему заряда скважины — и
            сохраняет выбранный вариант в технический паспорт. Настройки листа
            сохраняются автоматически отдельно для каждого объекта работ.
          </p>

          <h4>Порядок работы</h4>
          <ul>
            <li>
              <b>Юнит и объект.</b> Юнит в шапке сужает список объектов; объекты без
              юнита видны при любом выборе. При выборе объекта юнит подставляется из
              справочника.
            </li>
            <li>
              <b>Исходные данные.</b> Порода, ВВ, высота уступа, перебур, кондиционный
              кусок, допустимый негабарит и диаметры коронок — затем «Рассчитать
              варианты».
            </li>
            <li>
              <b>Варианты сетки.</b> По строке на диаметр; выбранная строка — основа
              для схемы заряда, её показатели — на плашках над таблицей. «Перенести в
              проект» открывает вариант на вкладке «Проектирование».
            </li>
            <li>
              <b>Схема заряда.</b> Два варианта заряда на выбранной сетке: тип ВВ,
              недозаряд, детонаторы и НСИ; объём блока и доля дополнительных скважин
              общие для обоих.
            </li>
            <li>
              <b>Паспорт.</b> Выберите вариант заряда и сохраните паспорт. Кнопка
              «Экономика» открывает уже сохранённый паспорт: чтобы передать текущий
              расчёт, сначала сохраните новый.
            </li>
          </ul>

          <h4>Показатели</h4>
          <ul>
            <li>
              <b>q, кг/м³</b> — удельный расход ВВ: наименьший, при котором доля
              негабарита не превышает допустимую.
            </li>
            <li>
              <b>W, м</b> — линия наименьшего сопротивления; шаг сетки a = W × коэффициент
              сетки a/W.
            </li>
            <li>
              <b>x50, мм</b> — средний размер куска после взрыва.
            </li>
            <li>
              <b>Негабарит, %</b> — доля кусков крупнее кондиционного размера.
            </li>
          </ul>
        </div>
      </dialog>
    </>
  );
}
