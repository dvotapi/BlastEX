// Справка «?» панели «Съёмка бурения» (TASK-014, PR 5а). Правила — `Docs/SURVEY_IMPORT.md`.
import { useRef, type MouseEvent } from "react";

export function SurveyHelp() {
  const ref = useRef<HTMLDialogElement>(null);

  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  return (
    <>
      <button
        type="button"
        className="topbar-icon-button"
        aria-label="Справка по съёмке бурения"
        title="Справка"
        onClick={() => ref.current?.showModal()}
      >
        ?
      </button>
      <dialog ref={ref} className="cad-help" aria-labelledby="survey-help-title" onClick={onBackdropClick}>
        <header>
          <b id="survey-help-title">Съёмка бурения: справка</b>
          <button type="button" aria-label="Закрыть справку" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="cad-help-body">
          <p>
            Файл маркшейдера (CSV, TXT, XLSX, DXF) с фактическими устьями пробуренных скважин. Точки
            сопоставляются со скважинами проекта, оцениваются по допускам паспорта на бурение, а
            «Применить» переносит факт в проект одним шагом отмены.
          </p>
          <h4>Файл</h4>
          <p>
            Таблица с заголовками несёт глубину, угол, азимут и воду; файл выноса для GNSS — только
            координаты. Описание точки выноса («L10.7») глубиной не считается: глубину введите в
            таблице вручную. Таблица бывает и в TXT — через табуляцию или через пробелы (тогда названия
            колонок — одним словом, без пустых ячеек). Если колонки не узнаны, выберите их в блоке
            «Колонки»; «— нет —» у найденной колонки (например, ненадёжной отметки) её выключает.
            Глубина не больше нуля не читается — скважина «глубина не замерена». Файл выноса BlastEX узнаётся по профилю в имени. Угол — от вертикали, как в
            проекте.
          </p>
          <p>
            По-русски X — север, Y — восток. Если точки легли зеркально, нажмите «Поменять» — это
            работает и для таблицы, и для файла выноса, и для DXF. Профили выноса из справочника
            объекта при чтении пока не поддерживаются: выберите подходящий формат вручную.
          </p>
          <h4>Сопоставление</h4>
          <p>
            Сначала вручную выбранная скважина, затем имя точки (с номером блока или без), затем
            близость в плане — не дальше двух допусков по устью. Лишние точки (репер, станция, забой
            «_T») остаются «точкой без скважины»: привяжите их сами или пропустите. Любую точку — и
            сопоставленную по имени — можно привязать к другой скважине, оставить «без скважины» или
            пропустить. Выбор относится к строке файла: две точки с одним именем решаются отдельно.
          </p>
          <h4>Оценка</h4>
          <p>
            Допуски берутся из паспорта на бурение (глубина, устье, угол, ЛСПП, шаг); нет паспорта —
            берутся стандартные значения: 0,3 м, 0,3 м, 1°, 5 %, 5 %. Глубина сравнивается с нужной длиной при снятой отметке устья, подошва
            проектная. ДОБУРИТЬ, ПЕРЕБУР, СМЕЩЕНИЕ, УГОЛ, ЛСПП, ШАГ — вне допуска; «без изменения» —
            в пределах округления файла.
          </p>
          <h4>Применить</h4>
          <p>
            Устье, отметка, длина, угол и вода скважин переносятся из съёмки, заряды пересчитываются
            только у изменённых скважин, коммутация помечается устаревшей. Проект становится «по
            съёмке». Коммутация устаревает, только если сменились устья или забои — одна вода её не
            трогает. Утверждённый проект не меняется: кнопка «Копия по съёмке» создаёт черновик и
            применяет съёмку к нему; если пока она создавалась, открыли другой проект, копия создана,
            но не открыта — откройте её в списке проектов. Закрытый проект съёмку не принимает. Недобур — отрицательный
            перебур при проектной подошве; проектный перебур скважина помнит, поэтому пересъёмка после
            добуривания покажет «ОК». Скважина без замера глубины в графы «Ф» проекта МВ и в сравнение
            «Факт бурения» глубину не передаёт — там «—».
          </p>
          <h4>Старый блок</h4>
          <p>
            «Съёмка старого блока» сохраняет точки блока, которого нет в проектах, на объекте. Сверить
            их не с чем, поэтому проверьте формат файла и при надобности отметьте «Поменять X и Y»;
            после загрузки окно скажет, как файл прочитан, и покажет предупреждения. Тот же файл для
            того же блока второй раз не принимается.
          </p>
        </div>
      </dialog>
    </>
  );
}
