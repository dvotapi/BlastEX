const ORIGIN_NOTES: Record<string, string> = {
  template: "роль взята из шаблона слоёв объекта — так был размечен прошлый файл этого маркшейдера.",
  auto: "роль подобрана по имени слоя и типу объектов на нём.",
  z: "верхняя или нижняя бровка определена по отметке линии относительно подошвы.",
  manual: "роль назначена вручную; повторный разбор файла её не меняет.",
};

export function CadImportHelp({ meta }: { meta: CadMeta | null }) {
  const ref = useRef<HTMLDialogElement>(null);

  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  const roles = meta ? [...meta.roles, ...meta.layer_roles] : [];

  return (
    <>
      <button
        type="button"
        className="topbar-icon-button"
        aria-label="Справка по импорту чертежа"
        title="Справка"
        onClick={() => ref.current?.showModal()}
      >
        ?
      </button>
      <dialog ref={ref} className="cad-help" aria-labelledby="cad-help-title" onClick={onBackdropClick}>
        <header>
          <b id="cad-help-title">Импорт чертежа: справка</b>
          <button type="button" aria-label="Закрыть справку" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="cad-help-body">
          <p>
            Окно читает чертёж маркшейдера целиком — линии, точки, условные знаки и подписи
            отметок — и раскладывает его по ролям: что здесь контур блока, что бровки, что
            отметки поверхности, а что ситуация карьера. Роли сохраняются сразу, отдельной
            кнопки «Сохранить» нет. Файлов можно загрузить несколько — переключатель «Файл»
            над таблицей.
          </p>

          <h4>Что присылает маркшейдер</h4>
          <ul>
            <li>
              <b>Контур блока</b> — замкнутой полилинией или набором открытых линий: участки
              бровок, линия отрезки по массиву, край дороги.
            </li>
            <li>
              <b>Отметки поверхности</b> — 3D-полилинии съёмки, горизонтали с одной отметкой,
              точки и знаки с подписями.
            </li>
            <li>
              <b>Бровки горизонтов</b> — часто разбитые на фрагменты: у блока 66 на слое
              «Горизонт +410» 23 куска. В таблице фрагменты слоя свёрнуты в одну строку,
              стрелка раскрывает их по одному.
            </li>
            <li>
              <b>Ситуация</b> — контуры карьера, дороги, ЛЭП, склады, развалы соседних блоков.
            </li>
          </ul>

          <h4>Слои и роли</h4>
          <p>
            Роль назначается слою; у отдельного объекта её можно переопределить в раскрытой
            строке («По слою» возвращает роль слоя). Наведение на строку подсвечивает линии на
            чертеже, щелчок по линии находит её строку.
          </p>
          <ul aria-label="Роли слоёв">
            {roles.map((role) => (
              <li key={role.code}>
                <b>{role.label}.</b> {ROLE_NOTES[role.code] ?? ""}
              </li>
            ))}
          </ul>
          <p>
            Точке достаётся роль, подходящая точке: на слое бровок это «Отметки поверхности»,
            а точка без отметки (Z = 0 и без подписи) уходит в «Ситуацию».
          </p>

          <h4>Как роли назначаются сами</h4>
          <ul>
            <li>
              Слой со словом «блок» и номером (или «граница блока») с замкнутой линией — контур;
              открытые линии такого слоя — проектные линии.
            </li>
            <li>Слои «верхняя бровка» и «нижняя бровка» — бровки по имени.</li>
            <li>
              Слой «Горизонт …» или «бровка» с 3D-линиями — «Бровки (по Z)». Линия ниже
              «подошва + половина высоты уступа» — нижняя бровка, выше — верхняя. Подошва
              берётся из имени слоя («Горизонт +410» → 410 м) или из поля «Подошва», высота
              уступа — из паспорта (без неё 10 м). Нет ни того ни другого — бровки делятся по
              самому большому разрыву отметок.
            </li>
            <li>«Горизонтали» с одной отметкой — горизонтали, остальные линии слоя — характерные.</li>
            <li>Слои съёмки («Отметка», «Съёмка», «Рельеф», «Пикеты») — отметки поверхности.</li>
            <li>Всё остальное — ситуация; но точка или знак с отметкой на любом слое — отметка поверхности.</li>
            <li>Линия без отметки (Z = 0) на слое бровок бровкой не считается — это характерная линия.</li>
          </ul>

          <h4>Бейджи происхождения</h4>
          <ul aria-label="Бейджи происхождения">
            {(meta?.origins ?? []).map((origin) => (
              <li key={origin.code}>
                <b>{origin.label}.</b> {ORIGIN_NOTES[origin.code] ?? ""}
              </li>
            ))}
          </ul>

          <h4>Шаблон слоёв объекта</h4>
          <p>
            Соответствие «имя слоя → роль» хранится на объекте работ, выбранном в верхней
            панели. Первый файл пополняет шаблон всеми своими слоями, ручная смена роли слоя
            его переписывает. Следующий файл того же маркшейдера размечается по шаблону сам
            (бейдж «шаблон»); регистр букв и лишние пробелы в имени слоя не мешают. Объект не
            выбран — импорт работает, но шаблон не сохраняется.
          </p>

          <h4>Отметки из подписей</h4>
          <p>
            Точка или знак с Z = 0 получает отметку из ближайшей числовой подписи в радиусе
            3 м (поле «Радиус подписи»); подпись своего слоя важнее чужой, одна подпись — одной
            точке. Отметкой считается число с дробной частью или со знаком «+»: «410,84»,
            «+410»; «66» — это номер блока, не отметка. Подпись без точки поверхностью не
            становится.
          </p>

          <h4>Единицы и масштаб</h4>
          <p>
            Координаты читаются в метрах. Единицы в самом файле часто неверны — шаблон AutoCAD
            ставит миллиметры и для чертежей в метрах, — поэтому о них только сообщается.
            Если чертёж больше 20 км по стороне, он, скорее всего, в миллиметрах: окно
            предложит масштаб 0,001, кнопка перечитает файл.
          </p>

          <h4>DWG</h4>
          <p>
            DWG переводится в DXF на сервере. Если полный перевод прочитать не удалось,
            берётся упрощённый: геометрия, слои и отметки те же, но единиц и цветов слоёв
            в нём нет — об этом будет предупреждение.
          </p>

          <h4>Контур блока</h4>
          <p>
            Блок — это контур в плане и две поверхности: кровля и проектная подошва. Контур —
            простой замкнутый многоугольник; его отметка не используется: Z линии в чертеже — это
            отметка вычерчивания, а не рельеф. Получить контур можно четырьмя способами
            (вкладка «Контур»):
          </p>
          <ul aria-label="Способы контура">
            <li>
              <b>Готовый.</b> Замкнутая линия из чертежа — по умолчанию линия с ролью «Контур
              блока», так что блок строится без ручных действий. Почти замкнутая линия (разрыв
              концов не больше допуска) замыкается сама. Линия, замкнутая ещё при чтении чертежа
              (разрыв концов до 0,5 м, на шаге «Слои» — «замкнута по концам»), остаётся замкнутой при
              любом допуске.
            </li>
            <li>
              <b>Щелчок внутри.</b> Как штриховка в AutoCAD: линии отмеченных ролей разбиваются в
              пересечениях, берётся область, в которой щёлкнули. Концы ближе допуска сводятся,
              висячие концы соединяются мостом до 5 м (поле «Мост до, м») — контур, присланный
              кусками с разрывами, всё равно замкнётся. Если область дробится лишними линиями
              (например, фрагментами бровок внутри контура), снимите их роль во флажках «Линии
              контура».
            </li>
            <li>
              <b>Сборка.</b> Щёлкайте участки по порядку: «Участок» — кусок линии между соседними
              пересечениями, «По точкам» — кусок между двумя щелчками, «Отрезок» — прямая от
              вершины к вершине. Курсор привязывается к концу линии, пересечению, вершине и
              ближайшей точке. Направление каждого участка выбирается по ближайшему концу;
              «Развернуть» меняет его, «Отменить» и «Удалить» убирают участки. Если линий
              отмеченных ролей слишком много, пересечения не ищутся и «Участок» не работает —
              снимите лишние роли или собирайте «По точкам».
            </li>
            <li>
              <b>Блок по бровке.</b> Когда контура в чертеже нет: отметьте на верхней бровке начало и
              конец блока и задайте ширину в метрах или числом рядов × W (W — расстояние между
              рядами из паспорта). Тыл — бровка, смещённая на ширину в сторону от откоса, фланги — по
              нормали к бровке. Сторону откоса окно находит по нижней бровке не дальше 100 м от
              участка; если такой нет, выберите сторону сами. Результат правится как сборка
              («Править как сборку» есть у любого способа).
            </li>
          </ul>
          <p>
            <b>Замыкающий отрезок</b> — прямая, которой закрывается разрыв между участками больше
            допуска (0,5 м). На чертеже он пунктирный, его длина — в списке участков («замыкающий
            2,75 м»). Разрыв не больше допуска закрывается стыком: концы сводятся в среднюю точку.
          </p>
          <p>
            Фрагменты бровок перед построением сшиваются в одну линию: концы ближе 1 м, и следующий
            кусок продолжает направление (поворот до 60°); совпадающие концы ровно двух линий — при
            любом угле. Концы с перепадом отметок больше 1 м не сшиваются — это бровки разных
            уступов. Несшитые разрывы и изломы бровок видны на чертеже кружками.
          </p>

          <h4>Два контура и площади</h4>
          <p>
            У блока два контура с общими тылом и флангами. Контур по верхней бровке (S верх) — это
            контур паспорта, внутри него ставятся скважины. Контур по нижней бровке (S низ):
            фланги продлеваются от верхней бровки до нижней по своему направлению, откос между
            бровками добавляется к блоку. S ср = (S верх + S низ) / 2 — способ горизонтальных
            сечений. Введите площадь с блоковой карты, и окно покажет расхождение каждой площади.
            Нижней бровки нет — S низ = S верх и предупреждение «откос не учтён».
          </p>
          <p>
            Маркшейдеры называют площадью блока разное: площадь по верхней бровке, по нижней или их
            среднее. Переключатель «Площадь блока» задаёт, какая из трёх уходит в паспорт как
            площадь блока; выбор хранится на объекте работ и применяется к следующим файлам этого
            объекта (по умолчанию S ср). Сверьте с блоковой картой: какая площадь совпала — так и
            считает маркшейдер.
          </p>
          <p>
            Рёбра контура, целиком лежащие не дальше 1 м от верхней бровки, — свободная поверхность
            (на чертеже жирная линия): эта пометка уходит в паспорт, первый ряд считается от неё.
          </p>

          <h4>Построить блок</h4>
          <p>
            Кнопка неактивна, пока у контура есть ошибка: он не замкнут, пересекает сам себя (место
            отмечено на чертеже), не имеет площади или в нём есть ребро короче 0,05 м. Неактивна
            она и когда подошва не ниже бровки: отметка, которой нет в чертеже, остаётся
            паспортной, и высота уступа проверяется по итоговой паре. Перед
            проверкой контур выравнивается: обход против часовой стрелки, без повторов точек и
            вершин на прямой в пределах 1 см. Предупреждения (высота уступа вне 2–25 м, фланг не
            доходит до нижней бровки) видны у кнопки.
          </p>
          <p>
            Построение ставит в паспорт контур по верхней бровке, свободную поверхность, отметку
            бровки (по верхней бровке у откоса; линии без отметок, Z = 0, её не дают — остаётся
            паспортная) и подошвы (проектная отметка из поля «Подошва» или
            имени слоя «Горизонт +410»), а также оба контура и площади — паспорт не зависит от
            повторного импорта. Поверхности паспорта построение не меняет. Загрузка и разметка
            слоёв блок не меняют; если в паспорте уже есть скважины, построение спросит
            подтверждение: контур заменится, скважины, заряды и сеть очистятся.
          </p>
        </div>
      </dialog>
    </>
  );
}
