// Справка «?» паспорта на бурение (TASK-015, PR 6): безопасное расстояние s,
// первый ряд, проверка для инженера, выпуск ревизии, файл для GNSS-приёмника и
// DWG. Формулы — `design/drilling_passport.py` (`drill-v1`).
import { useRef, type MouseEvent } from "react";

export function DrillPassportHelp() {
  const ref = useRef<HTMLDialogElement>(null);

  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  return (
    <>
      <button
        type="button"
        className="topbar-icon-button"
        aria-label="Справка по паспорту на бурение"
        title="Справка"
        onClick={() => ref.current?.showModal()}
      >
        ?
      </button>
      <dialog ref={ref} className="cad-help" aria-labelledby="drill-help-title" onClick={onBackdropClick}>
        <header>
          <b id="drill-help-title">Паспорт на бурение: справка</b>
          <button type="button" aria-label="Закрыть справку" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="cad-help-body">
          <p>
            Паспорт строится по сохранённому проекту блока: скважины, их глубины, углы и номера
            берутся из «Проектирования», углы уступа, вылет оси и тексты — из справочников.
            Пустое поле формы — значение подставит расчёт; рядом подписано, откуда оно:
            «справочник», «проект блока», «расчёт». Введённое вручную помечено «вручную» и
            главнее справочника.
          </p>

          <p>
            Порядок работ (подготовка площадки, вынос точек, порядок обуривания, въезд, ЛЭП,
            совмещённые работы, приёмка) постоянен из паспорта в паспорт: новый паспорт берёт его из
            профиля паспорта объекта — справочник «Профиль паспорта на бурение», профиль задаётся у
            объекта. Нет профиля — тексты формы по умолчанию. В самом паспорте тексты правятся.
          </p>
          <p>
            Остальные поля нового паспорта заполняются сами. Объект и заказчик — из справочника
            объекта, горизонт — по скважинам (отметка подошвы). Подписи, ознакомление, «Составлен на
            основании», допуски, Wпред и станок — из прошлого паспорта того же объекта. Для первого
            паспорта объекта станок, его номер и диаметр коронки берутся из «Условий бурения» и
            единиц техники. Начало бурения — дата паспорта, окончание — по нормативу станка: объём
            бурения / (скорость × чистое время смены × 2 смены в сутки). Всё можно поправить.
          </p>

          <h4>Безопасное расстояние s</h4>
          <p>
            s — от верхней бровки до ближайшей точки опоры станка (гусениц). Это единственное
            число на схеме установки станка в паспорте:
          </p>
          <p>
            <b>s = roundup(max(2,0; Hs·(ctg γ − ctg α)), 0,1 м)</b>
          </p>
          <ul>
            <li>α — угол откоса рабочего уступа, γ — угол устойчивого борта (у объекта в справочнике или в паспорте; γ меньше α). Без них s не считается — паспорт не выпустить.</li>
            <li>Hs — проектная высота рабочего уступа: из паспорта, иначе у объекта, иначе наибольшая высота первого ряда H₁. Если H₁ больше Hs на 0,5 м и больше — предупреждение.</li>
            <li>s округляется вверх до 0,1 м и не бывает меньше 2,0 м.</li>
          </ul>

          <h4>Первый ряд</h4>
          <p>
            Первый ряд — скважины основной сетки, ближайшие к бровке (ранг 1 у свободной
            поверхности); стенки и вспомогательные скважины в него не входят. Если у блока нет
            бровки, первым рядом считаются скважины с наибольшим перебуром — с предупреждением.
            В таблице глубин паспорта первый ряд выделен красным.
          </p>

          <h4>Проверка для инженера</h4>
          <p>Эти числа в паспорт не печатаются, выпуск ревизии не блокируют:</p>
          <ul>
            <li>c_min = s − e — минимум от бровки до оси скважины первого ряда; e — вылет оси за передний край гусениц (у типа станка). Нет e — принято 0.</li>
            <li>c — принятое расстояние от бровки до оси первого ряда; не задано — берётся c_min.</li>
            <li>W = H·ctg α + c − d — ЛСПП у подошвы по каждой скважине первого ряда с её фактической высотой H; d — смещение забоя к откосу у наклонной скважины.</li>
            <li>Wпред — допустимая ЛСПП по проекту МВ: вводится в первом паспорте объекта, дальше переходит из паспорта в паспорт; без неё проверка W пропускается.</li>
          </ul>

          <h4>Предупреждения и ревизия</h4>
          <p>
            Ошибки (нет углов, нет скважин, скважина не вниз) выпуск запрещают. Каждое
            предупреждение нужно отметить «просмотрено» — так инженер подтверждает, что видел
            его. Ревизия неизменяема: PDF, чертёж, файл выноса и ведомость строятся только из
            неё и при повторе совпадают байт в байт. Неизменённый паспорт новую ревизию не
            выпускает. Предпросмотр показывает черновик с пометкой «Черновик — не для работы».
          </p>

          <h4>Файл для GNSS-приёмника</h4>
          <p>Профиль выбирается по полевому ПО приёмника:</p>
          <ul>
            <li><b>PNEZD (CSV)</b> — точка, север, восток, отметка, описание: Trimble Access, Carlson / SurvCE, South / Stonex, Emlid Flow, CHC LandStar.</li>
            <li><b>PENZD (CSV)</b> — для контроллеров с порядком «восток, север».</li>
            <li><b>PNEZ (TXT)</b> — через пробел, без описания, для старого полевого ПО.</li>
            <li><b>DXF точек</b> — для контроллеров, которые выносят точки из DXF.</li>
          </ul>
          <p>
            Имя точки — блок и номер скважины («66-1-01»), только латиница и не длиннее 16
            знаков; длинное название блока не даст сформировать файл — замечание появится у
            поля «Блок». Профиль по умолчанию задан у объекта.
          </p>
          <p>
            <b>Приёмник должен работать в той же локализации (МСК) объекта</b>, что и чертёж
            маркшейдера: координаты в файле — в СК объекта без пересчёта, самой СК в файле нет.
            Локализацию на контроллере настраивает маркшейдер.
          </p>

          <h4>Чертёж DXF и DWG</h4>
          <p>
            DXF открывается в AutoCAD и nanoCAD и ложится на чертёж маркшейдера без сдвига.
            DWG пока не формируется: кнопка «DWG» отдаёт DXF — в AutoCAD его можно
            «Сохранить как» DWG.
          </p>
        </div>
      </dialog>
    </>
  );
}
