// Справка «?» окна проекта массового взрыва (TASK-018, PR 6): проект и слои,
// порядок работы, откуда значения, что считается само, запас в наряде,
// печать комплекта.
import { useRef, type MouseEvent } from "react";

export function MassBlastHelp() {
  const ref = useRef<HTMLDialogElement>(null);

  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  return (
    <>
      <button type="button" className="topbar-icon-button" aria-label="Справка по проекту массового взрыва" title="Справка"
        onClick={() => ref.current?.showModal?.()}>
        ?
      </button>
      <dialog ref={ref} className="cad-help" aria-labelledby="mb-help-title" onClick={onBackdropClick}>
        <header>
          <b id="mb-help-title">Проект массового взрыва: справка</b>
          <button type="button" aria-label="Закрыть справку" onClick={() => ref.current?.close()}>×</button>
        </header>
        <div className="cad-help-body">
          <p>
            Проект оформляется по утверждённой форме ВМ.09.03. Он состоит из <b>проекта</b> — титул, технический
            расчёт, таблица параметров, распорядок, графика Г.1–Г.5 — и <b>слоёв дня взрыва</b>: наряд-путёвка,
            уведомление, акт готовности, талон-допуск, акт приёмки, исполнительная таблица («Факт»). Слой ссылается
            на ревизию проекта, но не меняет её; у слоя свои данные, ревизии и подписи.
          </p>

          <h4>Порядок работы</h4>
          <ol>
            <li>Создайте проект: дата и время взрыва, блоки. Остальное заполнится само.</li>
            <li>Заполните вкладки и нажмите «Проверить» — сервер посчитает зоны, расход и документы и покажет замечания.</li>
            <li>«Предпросмотр» каждого документа — PDF с пометкой «ЧЕРНОВИК».</li>
            <li>«Выпустить ревизию на согласование» — проект фиксируется; согласуют назначенные учётки ролей.</li>
            <li>«Утвердить проект» — открывается вкладка «День взрыва»: наряд-путёвка, уведомления, акт готовности, «Факт».</li>
            <li>«Взрыв произведён» — открываются талон-допуск и акт приёмки; в наряде — графы «выдано / израсходовано / возвращено».</li>
            <li>«Закрыть проект» — когда документы дня взрыва выпущены.</li>
          </ol>

          <h4>Откуда значения</h4>
          <p>
            Скважины, заряды и сеть — из сохранённых проектов блоков «Проектирования». Реквизиты объекта, подписанты,
            удельный расход по ТП, коэффициенты безопасности, тексты распорядка, адресаты уведомлений — из
            справочников объекта. Пустое поле формы — значение подставит справочник или расчёт; оно показано серой
            подсказкой под полем. Введённое в проекте главнее справочника.
          </p>
          <p>
            Новый проект берёт из прошлого проекта того же объекта людей (составил, проверил, подписанты,
            согласования, маркшейдер, персонал, учётки ролей) и постоянные тексты распорядка. № проекта, даты, посты,
            точки на плане и охраняемые объекты не переносятся: место и день взрыва другие.
          </p>

          <h4>Что считается само</h4>
          <p>
            Опасные зоны по ФНП 494 (разлёт, ударная воздушная волна, сейсмика; кратно 50 м), расход ВМ по проекту,
            технический расчёт, таблица параметров (масса — кратно 5 кг), время сигналов распорядка (предупредительный
            — за час, осмотр — не ранее +15 мин, допуск — не ранее +30 мин), расстояния до охраняемых объектов.
            Ручная опасная зона — не меньше расчётной и с причиной.
          </p>

          <h4>Посты и план</h4>
          <p>
            Посты, взрывная станция, укрытие и место сбора ставятся точками на плане Г.5: выберите, что ставить, и
            щёлкните по плану; точку можно перетащить. Пост внутри зоны для людей — предупреждение.
          </p>

          <h4>Наряд-путёвка и запас</h4>
          <p>
            «К выдаче» = по проекту + запас. Запас — на случай, если понадобится; расчёты проекта (зоны, Q_э, сейсмика)
            он не меняет. Нужно больше ВМ после выдачи — новая наряд-путёвка, а не правка этой.
          </p>

          <h4>Перенос заново</h4>
          <p>
            Если проект перевыпущен, факт в проектах блоков изменился или выпущена новая ревизия «Факта», слой
            предлагает перенести данные заново. Сначала показывается, что изменится; введённое вручную сохраняется.
          </p>

          <h4>Печать</h4>
          <p>
            «Весь комплект» — архив с документами по одному и общим PDF для двусторонней печати: каждый документ
            начинается с лицевой стороны листа, пустые обороты помечены. Графику Г.1–Г.5 печатать в масштабе 100 %,
            без «вписать в страницу» — иначе масштаб на бумаге неверен.
          </p>
        </div>
      </dialog>
    </>
  );
}
