import { useRef, type MouseEvent } from "react";
import { createPortal } from "react-dom";
import { useTopbarSlot } from "../../app/topbarSlot";

/**
 * Справка вкладки «Экономика блока»: что здесь считается и как этим пользоваться.
 *
 * Заголовок и вводный абзац раньше стояли прямо на странице — сметчик читал
 * их при каждом открытии вкладки. Справка убирает их из поля зрения, но не
 * теряет: содержание то же, только по требованию, через кнопку. Видимый
 * заголовок страницы ушёл в диалог по просьбе — `h2` ниже существует только
 * для программ чтения с экрана, глазами он не виден (см. `.sr-only`).
 *
 * Текст пересказывает смету-конструктор (семь разделов `estimateModel.ts`,
 * бейджи происхождения `estimate/OriginBadge.tsx`, режимы бурения
 * `DrillingSection.tsx`, кольцо структуры и лестницу цены `sidebar/`,
 * сценарии `scenario.ts`) своими словами — подробное описание того же самого
 * для разработчика лежит в `Docs/BLOCK_ECONOMICS_UI.md`; при изменении
 * состава разделов или полей сверьте формулировки в обоих местах.
 */
export function EconomicsHelp() {
  const ref = useRef<HTMLDialogElement>(null);
  // Круглая иконка «?» в правой части шапки — если слот ещё не смонтирован
  // (тесты компонента без AppShell), кнопка рисуется на своём обычном месте
  // на странице, тем же приёмом, что и полоса листа «Расчёт».
  const topbarSlot = useTopbarSlot();

  // Нативный `dialog` закрывается по Esc сам — обработчик не нужен. По
  // клику на подложку — нет, это здесь единственное, что приходится делать
  // руками: клик по `::backdrop` бьёт по самому `<dialog>`, клик по
  // содержимому — по внутренним элементам, поэтому цель события отличает
  // одно от другого без отдельной обёртки.
  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  const openButton = (
    <button
      type="button"
      className="topbar-icon-button"
      aria-label="Справка"
      title="Справка"
      onClick={() => ref.current?.showModal()}
    >
      ?
    </button>
  );

  return (
    <>
      <h2 className="sr-only">Экономика блока</h2>
      {topbarSlot ? createPortal(openButton, topbarSlot) : openButton}
      <dialog
        ref={ref}
        className="economics-help"
        aria-labelledby="economics-help-title"
        onClick={onBackdropClick}
      >
        <header>
          {/* Нативный `dialog` не берёт имя из содержимого само — без
              `aria-labelledby` программа чтения объявила бы диалог безымянным. */}
          <b id="economics-help-title">Экономика блока</b>
          <button type="button" aria-label="Закрыть" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="economics-help-body">
          <p>
            Вкладка считает себестоимость и цену кубометра горной массы по техническому
            паспорту блока и пакету работ прямо в строках сметы-конструктора: семь
            разделов, у каждой строки — количество, единица, цена, сумма и бейдж, откуда
            взята цифра. Геометрия (объём, погонаж, скважины, НСИ) — только для чтения:
            её посчитал технический паспорт, здесь её не правят. Расчёт — на бэкенде,
            фронт лишь выбирает записи из справочников и показывает уже посчитанные строки.
          </p>

          <h4>Что вводится</h4>
          <ul>
            <li>
              <b>Взрывчатые материалы.</b> Материал каждой роли номенклатуры (основное ВВ,
              промежуточный детонатор, скважинные и поверхностные НСИ) — из справочника;
              количество и сумму считает модель по паспорту. Электродетонаторы —
              исключение: паспорт их не считает, число вводится вручную рядом с
              наименованием, по умолчанию — ноль.
            </li>
            <li>
              <b>Бурение.</b> Переключатель «Собственными силами» / «Субподряд». Своими
              силами — станок из справочника и его плановые смены в месяц; субподряд —
              подрядчик, тариф из его справочника ставок либо ручная ставка, ₽/м, с
              кнопкой «Сохранить тариф в справочник».
            </li>
            <li>
              <b>Техника и оборудование.</b> Четыре роли — буровая установка, СЗМ,
              доставщик ВМ, тягач эмульсии: выбор единицы из справочника и плановые смены
              в месяц (смены на блок считает модель). Роль без техники не занимает
              строку — кнопка «+ Добавить технику» показывает скрытые роли.
            </li>
            <li>
              <b>Персонал.</b> Состав бригады: должность (только прямые), численность и
              смены на блок; «Сбросить к нормативу» возвращает запись к шаблону пакета.
            </li>
            <li>
              <b>Производственные услуги.</b> То, что справочник не знает заранее:
              проживание и питание, медосмотр, услуги сторонних организаций. Сумма живёт в
              параметрах прогона, поэтому смета воспроизводима без справочника. Кнопка
              «В справочник» публикует правило затрат и убирает строку отсюда — иначе при
              следующем расчёте сумма посчиталась бы дважды.
            </li>
            <li>
              <b>Прочие параметры.</b> ОХР, рентабельность, НДС — пустое поле означает
              норматив из справочника.
            </li>
          </ul>

          <h4>Что считает модель</h4>
          <ul>
            <li>
              <b>Смета блока.</b> Семь разделов конструктора (взрывчатые материалы,
              бурение, персонал, техника, ГСМ, услуги, постоянные и
              общепроизводственные расходы) — другая группировка строк, чем «слой →
              раздел» бумажной сметы на вкладке «Структура затрат». Раздел показан всегда,
              даже пустым. Бейдж у каждой строки — Паспорт, Расчёт, Справочник, Норматив
              или Ручной — говорит, откуда взята величина, а не только цифра сама по себе;
              формула раскрывается по клику на «⋯» → «Формула».
            </li>
            <li>
              <b>Стоимость бурения.</b> Переменная часть метра (оснастка, ДТ, запчасти,
              допуск экипажа) и постоянная (амортизация и страховка по плановым сменам) —
              из условий бурения станка, а не введены вручную; разложение метра можно
              открыть рядом, не уходя со страницы.
            </li>
            <li>
              <b>Структура себестоимости.</b> Кольцевая диаграмма — доля каждого из семи
              разделов, ₽ или ₽/м³; клик по сегменту раскрывает и подсвечивает
              соответствующий раздел сметы.
            </li>
            <li>
              <b>Цена блока.</b> Лестница: полная себестоимость → общехозяйственные
              расходы → себестоимость с ОХР → рентабельность → выручка без НДС → с НДС.
            </li>
            <li>
              <b>Модель сообщает.</b> Два разных предупреждения под одним заголовком.
              Незаполненная норма — знак пустого места в справочнике: строка всё равно
              посчитана, просто нулём или по грубой оценке. Нехватка ёмкости склада —
              не то же самое: справочник заполнен полностью, но площади не хватает под
              плановый объём, и это настоящее узкое место, а не повод считать строку
              неточной.
            </li>
          </ul>

          <h4>Сценарии и сравнение</h4>
          <p>
            До четырёх черновиков открываются параллельно и переключаются селектором в
            шапке; «Дублировать» копирует параметры активного черновика в новый.
            «Сохранить» кладёт текущий набор параметров и результат под именем — так
            сравнивают варианты пакета работ или бригады; черновик с несохранёнными
            правками помечен «Черновик · не сохранено». До трёх сохранённых сценариев
            сравниваются построчно на вкладке «Сравнение сценариев»; чувствительность
            показывает, как полная цена м³ реагирует на ±10&nbsp;% по каждому параметру;
            вкладка «История» хранит все сохранённые сценарии паспорта, каждый можно
            открыть черновиком или выгрузить в XLSX.
          </p>
        </div>
      </dialog>
    </>
  );
}
