import { useRef, type MouseEvent } from "react";
import { createPortal } from "react-dom";
import { useTopbarTitleSlot } from "../../app/topbarSlot";

/**
 * Справка вкладки «Экономика блока»: что здесь считается и как этим пользоваться.
 *
 * Заголовок и вводный абзац раньше стояли прямо на странице — сметчик читал
 * их при каждом открытии вкладки. Справка убирает их из поля зрения, но не
 * теряет: содержание то же, только по требованию, через кнопку. Видимый
 * заголовок страницы ушёл в диалог по просьбе — `h2` ниже существует только
 * для программ чтения с экрана, глазами он не виден (см. `.sr-only`).
 *
 * Текст пересказывает поля `ParametersPanel`, `NomenclaturePanel`,
 * `ServicesPanel` и разделы `CostStructure`/`PricePanel` своими словами —
 * при изменении их состава сверьте формулировки здесь.
 */
export function EconomicsHelp() {
  const ref = useRef<HTMLDialogElement>(null);
  // Рядом с заголовком «Экономика блока» в шапке — если слот ещё не
  // смонтирован (тесты компонента без AppShell), кнопка рисуется на своём
  // обычном месте на странице, тем же приёмом, что и полоса листа «Расчёт».
  const titleSlot = useTopbarTitleSlot();

  // Нативный `dialog` закрывается по Esc сам — обработчик не нужен. По
  // клику на подложку — нет, это здесь единственное, что приходится делать
  // руками: клик по `::backdrop` бьёт по самому `<dialog>`, клик по
  // содержимому — по внутренним элементам, поэтому цель события отличает
  // одно от другого без отдельной обёртки.
  function onBackdropClick(event: MouseEvent<HTMLDialogElement>) {
    if (event.target === ref.current) ref.current?.close();
  }

  const openButton = (
    <button type="button" className="secondary-button" onClick={() => ref.current?.showModal()}>
      Справка
    </button>
  );

  return (
    <>
      <h2 className="sr-only">Экономика блока</h2>
      {titleSlot ? createPortal(openButton, titleSlot) : openButton}
      <dialog ref={ref} className="economics-help" onClick={onBackdropClick}>
        <header>
          <b>Экономика блока</b>
          <button type="button" aria-label="Закрыть" onClick={() => ref.current?.close()}>
            ×
          </button>
        </header>
        <div className="economics-help-body">
          <p>
            Вкладка считает себестоимость и цену кубометра горной массы по техническому
            паспорту блока и пакету работ. Геометрия (объём, погонаж, скважины, НСИ) —
            только для чтения: её посчитал технический паспорт, здесь её не правят.
          </p>

          <h4>Что вводится</h4>
          <ul>
            <li>
              <b>Номенклатура блока.</b> Основное ВВ, промежуточные детонаторы, скважинные,
              поверхностные и стартовые НСИ, электродетонаторы — только наименование.
              Количество уже посчитал технический паспорт, цену — справочник.
            </li>
            <li>
              <b>Параметры модели.</b> Всё, чего нет в паспорте: буровой станок и его
              плановые смены, техника блока (СЗМ, доставщик ВМ, тягач эмульсии) с
              плановыми сменами в месяц, состав бригады, ОХР, рентабельность, НДС —
              пустое поле означает норматив из справочника.
            </li>
            <li>
              <b>Услуги и прочие расходы.</b> То, что справочник не знает заранее:
              проживание и питание, медосмотр и выпуск на линию, услуги сторонних
              организаций. Сумма живёт в параметрах прогона, поэтому смета
              воспроизводима без справочника. Кнопка «В справочник» публикует правило
              затрат и убирает строку отсюда — иначе при следующем расчёте сумма
              посчиталась бы дважды. Код правила (вида
              «SERVICE_ПРЕДРЕЙСОВЫЙ_МЕДОСМОТР») — техническое имя записи в справочнике,
              переносить его в разговоре с бригадой не нужно; название услуги остаётся
              человеческим.
            </li>
          </ul>

          <h4>Что считает модель</h4>
          <ul>
            <li>
              <b>Стоимость бурения.</b> Переменная часть метра (оснастка, ДТ, запчасти,
              допуск экипажа) и постоянная (амортизация и страховка по плановым сменам) —
              из условий бурения станка, а не введены вручную.
            </li>
            <li>
              <b>Смета блока.</b> Разделы бумажной сметы (расходы на ВМ, бурение,
              логистика ВМ, суточные, ФОТ, ГСМ, амортизация, общепроизводственные) внутри
              слоёв себестоимости (переменные → прямые блока → постоянные юнита →
              нераспределённые). Строка показывает норму, единицу, цену и сумму —
              формула раскрывается по клику.
            </li>
            <li>
              <b>Цена блока.</b> Лестница: полная себестоимость → общехозяйственные
              расходы → себестоимость с ОХР → рентабельность → выручка без НДС.
              Маржинальная себестоимость — цена, ниже которой блок убыточен сам по себе;
              на бумаге её нет, здесь она отдельной карточкой.
            </li>
            <li>
              <b>Модель сообщает.</b> Предупреждения о незаполненных нормах и узких местах
              склада — не ошибка, а знак незаполненного места в справочнике: строка всё
              равно посчитана, просто нулём или по грубой оценке.
            </li>
          </ul>

          <h4>Сценарии и сравнение</h4>
          <p>
            «Сохранить сценарий» кладёт текущий набор параметров и результат под именем:
            так сравнивают варианты пакета работ или бригады. До трёх сохранённых
            сценариев сравниваются построчно; чувствительность показывает, как полная
            цена м³ реагирует на ±10&nbsp;% по каждому параметру.
          </p>
        </div>
      </dialog>
    </>
  );
}
